"""Build the population-wide verification matrix over every MLII record.

Two modes, both writing docs/verification_matrix.md:

    --mode reference   score the reference model on all records (no board needed)
    --mode hardware    additionally run each record on the board and require the
                       captured frame to be byte-identical to the golden one

Hardware mode swaps records by writing the sample store over JTAG, so the bitstream is
built once and never rebuilt. That is the whole point of the dual-port sample store:
the frozen global thresholds are the deployed configuration, and this phase measures
how that single configuration performs across the population rather than tuning
anything per record.

Usage:
    python python/scripts/verify_matrix.py
    python python/scripts/verify_matrix.py --mode hardware --port COM5
"""

from __future__ import annotations

import argparse
import importlib.util
import pathlib
import subprocess
import sys
import time

import _bootstrap  # noqa: F401
import numpy as np

from ecg_ref import config, detect, pipeline, preprocess

SCRIPTS = pathlib.Path(__file__).resolve().parent
REPO = config.REPO_ROOT


def _load_serial_rx():
    spec = importlib.util.spec_from_file_location(
        "serial_rx", SCRIPTS / "serial_rx.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def reference_row(record: str) -> dict:
    evaluation, encoded, _ = pipeline.evaluate_record(record)
    try:
        annotations = preprocess.read_annotations(record)
        score = detect.score_detection(encoded.detection.r_peaks, annotations)
        sensitivity, ppv = score.sensitivity, score.ppv
    except Exception:  # noqa: BLE001  (a record may have no annotation file)
        sensitivity = ppv = float("nan")

    return {
        "record": record,
        "cr": evaluation.compression_ratio,
        "prd_baseline": evaluation.prd_overall_baseline,
        "prd_strict": evaluation.prd_overall,
        "prd_qrs": evaluation.prd_qrs,
        "beats": evaluation.qrs_count,
        "sensitivity": sensitivity,
        "ppv": ppv,
        "saturated": evaluation.saturated,
        "escapes": evaluation.escapes,
        "words": len(encoded.words),
        "passed": evaluation.passed,
        "golden_words": encoded.words,
        "golden_payload": encoded.payload,
    }


def hardware_row(record: str, row: dict, serial_rx, args) -> dict:
    """Run one record on the board and compare the captured frame with golden."""
    load = subprocess.run(
        [args.xsct, str(REPO / "ps" / "run_hw.tcl"), "-record", record]
        + ([] if args.program else ["-no_program"]),
        capture_output=True, text=True, timeout=args.hw_timeout)
    if load.returncode != 0:
        row["hw_status"] = "load failed"
        row["hw_detail"] = load.stderr.strip().splitlines()[-1] if load.stderr else ""
        return row

    read_exact, link = serial_rx.reader_from_serial(
        args.port, config.UART_BAUD, args.timeout)
    try:
        frame, latency = serial_rx.read_transport_frame(read_exact)
    except serial_rx.FrameError as exc:
        row["hw_status"] = "no frame"
        row["hw_detail"] = str(exc)
        return row
    finally:
        link.close()

    row["hw_latency_cycles"] = latency
    row["hw_bytes"] = len(frame)
    if frame == row["golden_payload"]:
        row["hw_status"] = "bit-identical"
    else:
        got = [int.from_bytes(frame[i:i + 4], "big")
               for i in range(0, len(frame), 4)]
        row["hw_status"] = "DIFFERS"
        row["hw_detail"] = serial_rx._first_divergence(got, row["golden_words"])
    return row


def write_matrix(rows: list[dict], mode: str, path: pathlib.Path) -> bool:
    thresholds = ", ".join(f"{b}={config.BAND_THRESHOLD[b]}" for b in config.BAND_ORDER)
    hardware = mode == "hardware"

    lines = [
        "# Verification Matrix",
        "",
        f"Generated by `python/scripts/verify_matrix.py --mode {mode}`.",
        "",
        "One global, frozen threshold set is used for every record; there is no",
        "per-record tuning anywhere in this table.",
        "",
        f"- thresholds: {thresholds}",
        f"- gate: CR > {config.TARGET_CR}, PRD < {config.TARGET_PRD_OVERALL}% "
        f"({config.PRD_GATE_METRIC}-referenced), PRD on QRS exactly 0%",
        f"- records: {len(rows)} MLII-bearing MIT-BIH records, first "
        f"{config.N_SAMPLES:,} samples each",
        "",
    ]

    header = ("| Record | CR | PRD base % | PRD strict % | PRD QRS % | Beats | Se % "
              "| PPV % | Sat | Esc | Model |")
    divider = "|---|---|---|---|---|---|---|---|---|---|---|"
    if hardware:
        header += " Hardware |"
        divider += "---|"
    lines += [header, divider]

    for r in rows:
        line = (f"| {r['record']} | {r['cr']:.2f} | {r['prd_baseline']:.4f} | "
                f"{r['prd_strict']:.2f} | {r['prd_qrs']:.3f} | {r['beats']} | "
                f"{r['sensitivity']:.2f} | {r['ppv']:.2f} | {r['saturated']} | "
                f"{r['escapes']} | {'PASS' if r['passed'] else 'FAIL'} |")
        if hardware:
            line += f" {r.get('hw_status', 'not run')} |"
        lines.append(line)

    model_pass = sum(1 for r in rows if r["passed"])
    cr = np.array([r["cr"] for r in rows])
    prd = np.array([r["prd_baseline"] for r in rows])
    se = np.array([r["sensitivity"] for r in rows], dtype=float)

    lines += [
        "",
        "## Summary",
        "",
        f"- reference model: **{model_pass}/{len(rows)} records pass**",
        f"- CR: mean {cr.mean():.2f}, min {cr.min():.2f} "
        f"(record {rows[int(cr.argmin())]['record']}), max {cr.max():.2f}",
        f"- PRD baseline: mean {prd.mean():.4f}%, max {prd.max():.4f}% "
        f"(record {rows[int(prd.argmax())]['record']})",
        f"- PRD on QRS is exactly 0% on "
        f"{sum(1 for r in rows if r['prd_qrs'] == 0.0)}/{len(rows)} records",
        f"- detection sensitivity: mean {np.nanmean(se):.2f}%, "
        f"min {np.nanmin(se):.2f}%",
    ]

    ok = model_pass == len(rows)
    if hardware:
        matched = sum(1 for r in rows if r.get("hw_status") == "bit-identical")
        lines.append(f"- hardware: **{matched}/{len(rows)} frames byte-identical to "
                     f"the reference model**")
        latencies = [r["hw_latency_cycles"] for r in rows if "hw_latency_cycles" in r]
        if latencies:
            worst = max(latencies)
            seconds = worst / config.CLK_FREQ_HZ
            signal = config.N_SAMPLES / config.FS
            lines.append(f"- worst measured latency: {worst:,} PL cycles "
                         f"({seconds * 1e3:.2f} ms, {signal / seconds:.0f}x real time)")
        ok = ok and matched == len(rows)

        failures = [r for r in rows if r.get("hw_status") not in (None, "bit-identical")]
        if failures:
            lines += ["", "## Hardware failures", ""]
            for r in failures:
                lines.append(f"- {r['record']}: {r['hw_status']} "
                             f"{r.get('hw_detail', '')}")

    lines += ["", f"**Overall: {'PASS' if ok else 'FAIL'}**", ""]

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("records", nargs="*", default=None)
    parser.add_argument("--mode", choices=("reference", "hardware"),
                        default="reference")
    parser.add_argument("--port", default=None, help="serial port, for hardware mode")
    parser.add_argument("--xsct", default="xsct")
    parser.add_argument("--timeout", type=float, default=60.0,
                        help="serial read timeout per record")
    parser.add_argument("--hw-timeout", type=float, default=300.0,
                        help="timeout for the xsct program-and-run step")
    parser.add_argument("--program", action="store_true",
                        help="re-program the PL for every record (not normally "
                             "needed: swapping a record only rewrites the BRAM)")
    parser.add_argument("--out", default="verification_matrix.md")
    args = parser.parse_args()

    if args.mode == "hardware" and not args.port:
        parser.error("--mode hardware requires --port")

    records = args.records or [r for r in config.MLII_RECORDS
                               if (config.MITDB_DIR / f"{r}.hea").exists()]
    if not records:
        print("no records available; run download_mitdb.py first")
        return 1

    serial_rx = _load_serial_rx() if args.mode == "hardware" else None

    print(f"Verification matrix over {len(records)} record(s), mode={args.mode}")
    rows = []
    t0 = time.time()
    for record in records:
        try:
            row = reference_row(record)
        except Exception as exc:  # noqa: BLE001
            print(f"  {record}: ERROR {type(exc).__name__}: {exc}")
            continue

        if serial_rx is not None:
            # The PL is programmed once; only the first record needs it, unless the
            # caller explicitly asks for a re-program each time.
            first = not rows
            args.program = args.program or first
            row = hardware_row(record, row, serial_rx, args)
            args.program = False

        rows.append(row)
        suffix = f"  hw={row['hw_status']}" if "hw_status" in row else ""
        print(f"  {record}: CR={row['cr']:5.2f} "
              f"PRDbase={row['prd_baseline']:.4f}% "
              f"PRDqrs={row['prd_qrs']:.3f}% "
              f"{'PASS' if row['passed'] else 'FAIL'}{suffix}")

    if not rows:
        return 1

    path = REPO / "docs" / args.out
    ok = write_matrix(rows, args.mode, path)
    print(f"\nelapsed {time.time() - t0:.1f}s")
    print(f"wrote {path}")
    print("OVERALL: " + ("PASS" if ok else "FAIL"))
    return 0 if ok else 2


if __name__ == "__main__":
    sys.exit(main())
