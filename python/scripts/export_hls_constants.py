"""Generate hls/src/ecg_constants.h from config.py.

The HLS core must never carry its own copy of a constant. This script is the only
sanctioned way ecg_constants.h changes, so the Python reference model and the hardware
cannot drift apart; the HLS Tcl flow re-runs it before every build.
"""

from __future__ import annotations

import sys

import _bootstrap  # noqa: F401

from ecg_ref import config

TEMPLATE = """// AUTO-GENERATED by python/scripts/export_hls_constants.py -- DO NOT EDIT.
// Regenerate after any change to python/ecg_ref/config.py.
#ifndef ECG_CONSTANTS_H
#define ECG_CONSTANTS_H

// ---- Signal / dataset ----
#define ECG_FS                 {FS}
#define ECG_N_SAMPLES          {N_SAMPLES}
#define ECG_SAMPLE_BITS        {SAMPLE_BITS}
#define ECG_SAMPLE_MIN         ({SAMPLE_MIN})
#define ECG_SAMPLE_MAX         ({SAMPLE_MAX})

// ---- Detection: first-order shift-based IIR bandpass ----
#define ECG_IIR_LP_SHIFT       {IIR_LP_SHIFT}
#define ECG_IIR_HP_SHIFT       {IIR_HP_SHIFT}
#define ECG_IIR_FRAC_BITS      {IIR_FRAC_BITS}

// ---- Detection: energy, threshold, refractory ----
#define ECG_MA_LEN             {MA_LEN}
#define ECG_THRESH_SHIFT       {THRESH_SHIFT}
#define ECG_THRESH_FRAC_BITS   {THRESH_FRAC_BITS}
#define ECG_THRESH_FACTOR      {THRESH_FACTOR}
#define ECG_THRESH_INIT        {THRESH_INIT}
#define ECG_THRESH_WARMUP      {THRESH_WARMUP}
#define ECG_REFRACTORY         {REFRACTORY}
#define ECG_PEAK_SEARCH_BACK   {PEAK_SEARCH_BACK}
#define ECG_PEAK_SEARCH_FWD    {PEAK_SEARCH_FWD}

// ---- QRS window framing ----
#define ECG_QRS_PRE            {QRS_PRE}
#define ECG_QRS_POST           {QRS_POST}
#define ECG_QRS_WINDOW         {QRS_WINDOW}

// ---- Lossless path ----
#define ECG_GR_K_BITS          {GR_K_BITS}
#define ECG_GR_K_MAX           {GR_K_MAX}
#define ECG_GR_Q_ESCAPE        {GR_Q_ESCAPE}
#define ECG_GR_ESCAPE_BITS     {GR_ESCAPE_BITS}
#define ECG_ANCHOR_COUNT       {ANCHOR_COUNT}

// ---- Lossy path ----
#define ECG_DWT_LEVELS         {DWT_LEVELS}
#define ECG_DWT_BLOCK          {DWT_BLOCK}
// Upper bound on one lossy segment, so the PL coefficient buffers are provably large
// enough. Longer non-QRS runs are split into separate packets by both models.
#define ECG_MAX_LOSSY_SEGMENT  {MAX_LOSSY_SEGMENT}
#define ECG_T_A4               {T_A4}
#define ECG_T_D4               {T_D4}
#define ECG_T_D3               {T_D3}
#define ECG_T_D2               {T_D2}
#define ECG_T_D1               {T_D1}
#define ECG_QS_A4              {QS_A4}
#define ECG_QS_D4              {QS_D4}
#define ECG_QS_D3              {QS_D3}
#define ECG_QS_D2              {QS_D2}
#define ECG_QS_D1              {QS_D1}
#define ECG_RLE_RUN_BITS       {RLE_RUN_BITS}
#define ECG_RLE_RUN_MAX        {RLE_RUN_MAX}
#define ECG_RLE_VAL_BITS       {RLE_VAL_BITS}
#define ECG_RLE_VAL_MIN        ({RLE_VAL_MIN})
#define ECG_RLE_VAL_MAX        {RLE_VAL_MAX}
#define ECG_RLE_TOKEN_BITS     {RLE_TOKEN_BITS}

// ---- UART transport framing (PS firmware and host decoder) ----
#define ECG_UART_SYNC          0x{UART_SYNC_MAGIC:08X}u
#define ECG_UART_PREAMBLE      {UART_PREAMBLE_WORDS}
#define ECG_UART_BAUD          {UART_BAUD}
#define ECG_CLK_FREQ_HZ        {CLK_FREQ_HZ}

// ---- Bitstream ----
#define ECG_MAGIC_WORD         0x{MAGIC_WORD:08X}u
#define ECG_HEADER_WORDS       {HEADER_WORDS}
#define ECG_WORD_BITS          {WORD_BITS}
#define ECG_LEN_FIELD_BITS     {LEN_FIELD_BITS}
#define ECG_SYMCOUNT_BITS      {SYMCOUNT_FIELD_BITS}
#define ECG_TAG_QRS            {TAG_QRS}
#define ECG_TAG_NONQRS         {TAG_NONQRS}

// ---- Sizing limits for on-chip buffers ----
// Worst case beat count assumes an unbroken 300 bpm rhythm, which is far beyond any
// physiological record but keeps the R-peak index array safe from overflow.
#define ECG_MAX_PEAKS          {MAX_PEAKS}
// Longest non-QRS run the segment buffer must hold: a full record with no detections.
#define ECG_MAX_SEGMENT        {MAX_SEGMENT}
#define ECG_MAX_COEFFS         {MAX_SEGMENT}
// Loop-tripcount estimate for the packer's token loop. Reporting only: the loop is
// terminated by ECG_OP_END, not by this bound.
#define ECG_MAX_TOKENS         {MAX_TOKENS}
// Depth of the coder -> packer FIFO. Deep enough to absorb a burst of narrow fields
// (a long unary Golomb quotient) without stalling the coder, small enough for LUTRAM.
#define ECG_TOKEN_FIFO_DEPTH   {TOKEN_FIFO_DEPTH}

#endif  // ECG_CONSTANTS_H
"""


def render() -> str:
    max_peaks = (config.N_SAMPLES // config.REFRACTORY) + 2
    return TEMPLATE.format(
        FS=config.FS, N_SAMPLES=config.N_SAMPLES,
        SAMPLE_BITS=config.SAMPLE_BITS,
        SAMPLE_MIN=config.SAMPLE_MIN, SAMPLE_MAX=config.SAMPLE_MAX,
        IIR_LP_SHIFT=config.IIR_LP_SHIFT, IIR_HP_SHIFT=config.IIR_HP_SHIFT,
        IIR_FRAC_BITS=config.IIR_FRAC_BITS,
        MA_LEN=config.MA_LEN, THRESH_SHIFT=config.THRESH_SHIFT,
        THRESH_FRAC_BITS=config.THRESH_FRAC_BITS,
        THRESH_FACTOR=config.THRESH_FACTOR, THRESH_INIT=config.THRESH_INIT,
        THRESH_WARMUP=config.THRESH_WARMUP, REFRACTORY=config.REFRACTORY,
        PEAK_SEARCH_BACK=config.PEAK_SEARCH_BACK,
        PEAK_SEARCH_FWD=config.PEAK_SEARCH_FWD,
        QRS_PRE=config.QRS_PRE, QRS_POST=config.QRS_POST,
        QRS_WINDOW=config.QRS_WINDOW,
        GR_K_BITS=config.GR_K_BITS, GR_K_MAX=config.GR_K_MAX,
        GR_Q_ESCAPE=config.GR_Q_ESCAPE, GR_ESCAPE_BITS=config.GR_ESCAPE_BITS,
        ANCHOR_COUNT=config.ANCHOR_COUNT,
        DWT_LEVELS=config.DWT_LEVELS, DWT_BLOCK=config.DWT_BLOCK,
        MAX_LOSSY_SEGMENT=config.MAX_LOSSY_SEGMENT,
        T_A4=config.BAND_THRESHOLD["A4"], T_D4=config.BAND_THRESHOLD["D4"],
        T_D3=config.BAND_THRESHOLD["D3"], T_D2=config.BAND_THRESHOLD["D2"],
        T_D1=config.BAND_THRESHOLD["D1"],
        QS_A4=config.BAND_QUANT_SHIFT["A4"], QS_D4=config.BAND_QUANT_SHIFT["D4"],
        QS_D3=config.BAND_QUANT_SHIFT["D3"], QS_D2=config.BAND_QUANT_SHIFT["D2"],
        QS_D1=config.BAND_QUANT_SHIFT["D1"],
        RLE_RUN_BITS=config.RLE_RUN_BITS, RLE_RUN_MAX=config.RLE_RUN_MAX,
        RLE_VAL_BITS=config.RLE_VAL_BITS, RLE_VAL_MIN=config.RLE_VAL_MIN,
        RLE_VAL_MAX=config.RLE_VAL_MAX, RLE_TOKEN_BITS=config.RLE_TOKEN_BITS,
        UART_SYNC_MAGIC=config.UART_SYNC_MAGIC,
        UART_PREAMBLE_WORDS=config.UART_PREAMBLE_WORDS,
        UART_BAUD=config.UART_BAUD, CLK_FREQ_HZ=config.CLK_FREQ_HZ,
        MAGIC_WORD=config.MAGIC_WORD, HEADER_WORDS=config.HEADER_WORDS,
        WORD_BITS=config.WORD_BITS, LEN_FIELD_BITS=config.LEN_FIELD_BITS,
        SYMCOUNT_FIELD_BITS=config.SYMCOUNT_FIELD_BITS,
        TAG_QRS=config.TAG_QRS, TAG_NONQRS=config.TAG_NONQRS,
        MAX_PEAKS=max_peaks, MAX_SEGMENT=config.N_SAMPLES,
        MAX_TOKENS=config.MAX_TOKENS, TOKEN_FIFO_DEPTH=config.TOKEN_FIFO_DEPTH,
    )


def main() -> int:
    target = config.REPO_ROOT / "hls" / "src" / "ecg_constants.h"
    target.parent.mkdir(parents=True, exist_ok=True)
    text = render()
    if target.exists() and target.read_text(encoding="ascii") == text:
        print(f"{target} already up to date")
        return 0
    target.write_text(text, encoding="ascii")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
